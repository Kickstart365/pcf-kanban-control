const assert = require("node:assert/strict");
const path = require("node:path");
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "playwright");
(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1300, height: 900 } });
  const errors = []; page.on("pageerror", error => errors.push(error.message));
  try {
    await page.goto(`file://${path.resolve(__dirname, "../out/preview/interactions.html")}`);
    const field = name => page.locator(`[data-field-logical-name="${name}"]`);
    const edit = name => field(name).getByRole("button", { name: /^Aanpassen:/ });
    const draft = name => field(name).getByRole("textbox");
    const save = name => field(name).getByRole("button", { name: "Opslaan", exact: true });
    const cancel = name => field(name).getByRole("button", { name: "Annuleren", exact: true });
    await page.getByRole("button", { name: "Configuratie exporteren", exact: true }).click();
    const exportDialog = page.getByRole("dialog");
    const exportText = exportDialog.getByRole("textbox", { name: "Config (JSON)", exact: true });
    const exported = JSON.parse(await exportText.inputValue());
    assert.equal(exported.schemaVersion, 1);
    assert.equal(exported.board.allowCreateNew, false);
    assert.equal(exported.card.fields.transactioncurrencyid.hidden, true);
    assert.equal(JSON.stringify(exported).includes("Modern workplace"), false);
    await exportText.click();
    assert.equal(await exportText.evaluate(el => el.selectionEnd - el.selectionStart), (await exportText.inputValue()).length);
    await exportDialog.getByRole("button", { name: "JSON kopiëren", exact: true }).click();
    await exportDialog.getByRole("status").filter({ hasText: /Configuratie gekopieerd|Selecteer de JSON/ }).waitFor();
    await page.screenshot({ path: path.resolve(__dirname, "../out/preview/configuration-export.png"), fullPage: true });
    await exportDialog.getByRole("button", { name: "Sluiten", exact: true }).click();
    await exportDialog.waitFor({ state: "hidden" });
    await page.getByRole("button", { name: "Modern workplace", exact: true }).click();
    await page.locator("#test-pane:not([hidden])").waitFor();
    assert.equal(await page.evaluate(() => window.testState.creates), 1);
    await page.getByRole("button", { name: "Modern workplace", exact: true }).click();
    assert.equal(await page.evaluate(() => window.testState.creates), 1);
    await edit("closeprobability").click();
    assert.equal(await page.getByRole("button", { name: "Configuratie exporteren", exact: true }).isDisabled(), true);
    await draft("closeprobability").fill("101");
    await save("closeprobability").click();
    await field("closeprobability").getByRole("alert").waitFor();
    assert.equal(await draft("closeprobability").inputValue(), "101");
    assert.equal(await page.evaluate(() => window.testState.patches.length), 0);
    assert.equal(await page.getByRole("button", { name: "Modern workplace", exact: true }).isDisabled(), true);
    assert.equal(await page.getByRole("button", { name: "Kaart verplaatsen", exact: true }).count(), 0);
    await draft("closeprobability").fill("75"); await draft("closeprobability").press("Enter");
    await edit("closeprobability").waitFor();
    assert.equal(await page.evaluate(() => window.testState.row.closeprobability), 75);
    assert.equal(await page.evaluate(() => window.testState.opens), 2);
    await edit("estimatedvalue").click(); await draft("estimatedvalue").fill("48000,50");
    await page.screenshot({ path: path.resolve(__dirname, "../out/preview/inline-edit.png"), fullPage: true });
    await page.evaluate(() => { window.testState.held = true; });
    await save("estimatedvalue").click();
    assert.equal(await cancel("estimatedvalue").isDisabled(), true);
    await page.waitForFunction(() => !!window.releaseSave);
    await page.evaluate(() => { window.testState.held = false; window.releaseSave(); });
    await edit("estimatedvalue").waitFor();
    assert.equal(await page.evaluate(() => window.testState.row.estimatedvalue), 48000.5);
    assert.ok((await page.locator(".column-total-value").first().textContent()).includes("48.000,50"));
    await edit("description").click(); await draft("description").fill("Nieuw voorstel\nVrijdag bespreken");
    await save("description").click(); await edit("description").waitFor();
    assert.equal(await page.evaluate(() => window.testState.row.description), "Nieuw voorstel\nVrijdag bespreken");
    await edit("description").click(); await draft("description").fill("Niet opslaan"); await draft("description").press("Escape");
    await edit("description").waitFor();
    assert.equal(await page.evaluate(() => window.testState.patches.length), 3);
    await edit("estimatedvalue").click(); await draft("estimatedvalue").fill("60000");
    await page.evaluate(() => { window.testState.row.estimatedvalue = 50000; });
    await save("estimatedvalue").click(); await field("estimatedvalue").getByRole("alert").waitFor();
    assert.equal(await draft("estimatedvalue").inputValue(), "60000");
    assert.equal(await page.evaluate(() => window.testState.patches.length), 3);
    await cancel("estimatedvalue").click();
    await edit("description").click(); await draft("description").fill("Geen toegang");
    await page.evaluate(() => { window.testState.deny = true; }); await save("description").click();
    await field("description").getByText("Geen schrijfrechten", { exact: true }).waitFor();
    assert.equal(await draft("description").inputValue(), "Geen toegang");
    await cancel("description").click();
    assert.equal(await page.evaluate(() => window.testState.patches.length), 3);
    assert.equal(await page.evaluate(() => window.testState.dialogs), 0);
    assert.deepEqual(errors, []);
    console.log("Browser interactions passed: pane reuse, title/edit/drag separation, validation, Enter, Save, Cancel/Escape, generic text, updated totals, conflict and permission rejection.");
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
